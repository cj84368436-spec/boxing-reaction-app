import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'src/app/assets/sfx');
const source = join(root, 'scripts/sfx-source/qubodupPunch');
const rate = 44100;
const ffmpeg = process.env.FFMPEG_PATH || 'ffmpeg';
function wav(samples) {
  const b = Buffer.alloc(44 + samples.length * 2);
  b.write('RIFF'); b.writeUInt32LE(b.length - 8, 4); b.write('WAVEfmt ', 8);
  b.writeUInt32LE(16, 16); b.writeUInt16LE(1, 20); b.writeUInt16LE(1, 22);
  b.writeUInt32LE(rate, 24); b.writeUInt32LE(rate * 2, 28); b.writeUInt16LE(2, 32); b.writeUInt16LE(16, 34);
  b.write('data', 36); b.writeUInt32LE(samples.length * 2, 40);
  samples.forEach((x, i) => b.writeInt16LE(Math.round(Math.max(-1, Math.min(1, x)) * 32767), 44 + i * 2));
  return b;
}
await mkdir(out, { recursive: true });
// CC0 recorded impact source; source URL and attribution are alongside the FLACs.
for (const [kind, file, filter] of [
  ['hit', 'qubodupPunch01.flac', 'atrim=duration=0.38,asetpts=PTS-STARTPTS,highpass=f=65,lowpass=f=8500,volume=0.82,afade=t=out:st=0.25:d=0.13'],
  ['guard', 'qubodupPunch02.flac', 'atrim=duration=0.30,asetpts=PTS-STARTPTS,highpass=f=90,lowpass=f=1500,volume=0.72,afade=t=out:st=0.18:d=0.12'],
]) {
  const result = spawnSync(ffmpeg, ['-y', '-v', 'error', '-i', join(source, file), '-af', filter, '-ar', String(rate), '-ac', '1', '-c:a', 'pcm_s16le', '-map_metadata', '-1', join(out, kind + '.wav')], { encoding: 'utf8', windowsHide: true });
  if (result.error || result.status !== 0) throw new Error('FFmpeg failed: ' + (result.error?.message || result.stderr));
}
// A quiet, filtered air pass has no pitched success beep.
let state = 0x12345678, low = 0, slower = 0;
const air = Array.from({ length: Math.round(rate * .19) }, (_, i) => {
  state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
  const noise = state / 0xffffffff * 2 - 1;
  low += .24 * (noise - low); slower += .025 * (noise - slower);
  return (low - slower) * Math.pow(Math.sin(Math.PI * i / (rate * .19)), 2) * .7;
});
await writeFile(join(out, 'evade.wav'), wav(air));
const entries = await Promise.all(['hit', 'guard', 'evade'].map(async name => [name, 'data:audio/wav;base64,' + (await readFile(join(out, name + '.wav'))).toString('base64')]));
await writeFile(join(out, 'playtestSfxData.ts'), '// Generated by scripts/generate-playtest-sfx.mjs. Source: scripts/sfx-source/README.md\n// Data URIs avoid unsupported static WAV imports.\nexport const PLAYTEST_SFX_DATA_URIS = ' + JSON.stringify(Object.fromEntries(entries), null, 2) + ' as const;\n');
console.log('Generated recorded hit, muffled guard, and unpitched evade WAVs.');
